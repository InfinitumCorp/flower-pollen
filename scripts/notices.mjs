// Regenerates THIRD_PARTY_NOTICES.md from the license and NOTICE files of the direct runtime
// dependencies installed in node_modules. Run after adding or upgrading a dependency.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
const out = [
  '# Third-party notices',
  '',
  'Flower™ & POLLEN™ backend includes the following open-source packages as unmodified npm dependencies.',
  'No third-party source code is copied into this repository. Listing a project here does not imply',
  'that its authors endorse Infinitum Corporation or its products.',
  '',
  '<!-- generated by scripts/notices.mjs; do not edit by hand -->',
  '',
];
for (const name of Object.keys(pkg.dependencies ?? {}).sort()) {
  const dir = join('node_modules', name);
  const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const files = readdirSync(dir);
  const pick = (re) => files.filter((f) => re.test(f)).map((f) => readFileSync(join(dir, f), 'utf8').trim());
  const licenses = pick(/^(licen[cs]e|copying)(\.(md|txt))?$/i);
  const notices = pick(/^notice(\.(md|txt))?$/i);
  if (!licenses.length) throw new Error(`${name}: no license file found; check it before shipping`);
  const repo = String(meta.repository?.url ?? meta.repository ?? '').replace(/^git\+/, '').replace(/\.git$/, '');
  out.push(`## ${name} ${meta.version}`, '', `License: ${meta.license}${repo ? `  \nSource: ${repo}` : ''}`, '');
  for (const n of notices) out.push('### NOTICE', '', '```', n, '```', '');
  out.push('### License text', '', '```', licenses[0], '```', '');
}
writeFileSync('THIRD_PARTY_NOTICES.md', out.join('\n'));
console.log('wrote THIRD_PARTY_NOTICES.md');
